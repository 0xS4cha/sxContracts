CREATE TABLE IF NOT EXISTS `sx_contracts` (
    `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `title` VARCHAR(80) NOT NULL,
    `description` TEXT NULL,
    `category` VARCHAR(32) NOT NULL,
    `reward` INT UNSIGNED NOT NULL,
    `fee` INT UNSIGNED NOT NULL DEFAULT 0,
    `status` VARCHAR(16) NOT NULL DEFAULT 'open',
    `poster` VARCHAR(80) NOT NULL,
    `poster_name` VARCHAR(80) NOT NULL,
    `contractor` VARCHAR(80) NULL,
    `contractor_name` VARCHAR(80) NULL,
    `location` VARCHAR(120) NULL,
    `payout_to` VARCHAR(80) NULL,
    `payout_amount` INT UNSIGNED NOT NULL DEFAULT 0,
    `settled` TINYINT(1) NOT NULL DEFAULT 1,
    `created_at` INT UNSIGNED NOT NULL,
    `expires_at` INT UNSIGNED NOT NULL,
    `taken_at` INT UNSIGNED NULL,
    `closed_at` INT UNSIGNED NULL,
    PRIMARY KEY (`id`),
    KEY `status` (`status`),
    KEY `poster` (`poster`),
    KEY `contractor` (`contractor`),
    KEY `payout` (`payout_to`, `settled`)
);
